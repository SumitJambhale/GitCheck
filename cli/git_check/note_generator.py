from pathlib import Path
from typing import Dict, Any

class NoteGenerator:
    @staticmethod
    def format_commit_trailer(ticket: str, summary: str, agreed: bool) -> str:
        """
        Creates an auditable Git commit trailer containing the architectural summary.
        Note: Developer comprehension quiz scores are strictly confidential and omitted.
        """
        trailer = (
            f"\n\nGitCheck-Ticket: {ticket}\n"
            f"GitCheck-Status: {'Acknowledged-By-Author' if agreed else 'Pending-Verification'}\n"
            f"GitCheck-Summary: {summary}\n"
        )
        return trailer

    @staticmethod
    def write_pr_defense_card(output_dir: Path, data: Dict[str, Any]) -> Path:
        """
        Generates a standalone PR defense markdown card that can be pasted or attached to PRs.
        """
        output_dir.mkdir(parents=True, exist_ok=True)
        note_file = output_dir / "GITCHECK_DEFENSE_CARD.md"

        content = f"""# GitCheck Architectural Defense Card

| Field | Detail |
| :--- | :--- |
| **Ticket** | `{data.get('ticket_number', 'N/A')}` |
| **Branch** | `{data.get('branch_name', 'N/A')}` |
| **Commit** | `{data.get('commit_hash', 'N/A')}` |
| **Author** | {data.get('author_name', 'Developer')} |
| **Author Agreement** | {'✅ Confirmed' if data.get('agreed_with_changes') else '⚠️ Unconfirmed'} |

---

### Architectural Rationale & Change Intent
> {data.get('summary', 'No summary provided.')}

### Scope of Changes
- **Files Modified**: {len(data.get('detailed_analysis', {}).get('files_changed', []))}
- **Lines Added**: +{data.get('detailed_analysis', {}).get('lines_added', 0)}
- **Lines Removed**: -{data.get('detailed_analysis', {}).get('lines_removed', 0)}

---
*Generated by GitCheck Pre-Commit Verification Gate*
"""
        with open(note_file, "w", encoding="utf-8") as f:
            f.write(content)
        return note_file
